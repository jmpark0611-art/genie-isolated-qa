#!/usr/bin/env bash
set -Eeuo pipefail
umask 077
[[ "$(id -u)" != 0 && "$HOME" == /qa/home && "$(node --version)" == v22.23.5 ]]
[[ "$(/qa/supabase --version 2>/dev/null)" == 2.122.1 ]]
cd /qa/project
export SUPABASE_EXPERIMENTAL_STACK=1
stage=init
# The public CI log receives a fixed diagnostic category, never CLI output.
diagnostic_category() {
  local log="$1"
  if grep -Eiq 'unknown (subcommand|command)|unrecognized (argument|option)|not an allowed choice' "$log"; then
    echo unsupported-command-or-option
  elif grep -Eiq 'checksum|digest mismatch|hash mismatch' "$log"; then
    echo artifact-integrity
  elif grep -Eiq 'HTTP[^0-9]*[45][0-9]{2}|connection (timed out|refused)|failed to (download|fetch)|could not resolve host|ECONN' "$log"; then
    echo artifact-unavailable
  elif grep -Eiq 'supabase[.]lock.*(not found|stale)|invalid (configuration|config)|failed to (parse|load) config' "$log"; then
    echo lock-or-configuration
  elif grep -Eiq 'permission denied|could not look up effective user ID|user does not exist' "$log"; then
    echo permissions-or-user-lookup
  else
    echo unclassified
  fi
}
run_stage() {
  local log="$1" rc; shift
  if "$@" >"$log" 2>&1; then return 0; else rc=$?; fi
  printf 'DETAIL: disposable stack stage %s returned exit %d (%s).\n' "$stage" "$rc" "$(diagnostic_category "$log")" >&2
  return "$rc"
}
trap 'rc=$?; if ((rc)); then printf "%s\n" "STOP: disposable stack stage ${stage} failed." >&2; fi; exit "$rc"' EXIT
[[ ! -e "$HOME/.supabase/access-token" && ! -e supabase/.temp/project-ref ]]
stage=verify-disposable-identity
getent passwd "$(id -u)" >/dev/null
if [[ "${1:-}" == prepare ]]; then
  stage=generate-disposable-seed
  # Generated bytes are disposable, remain in the mounted temporary directory,
  # and are not displayed. Same secret is reused for this single project only.
  node --input-type=module -e 'import {randomBytes} from "node:crypto";process.stdout.write(randomBytes(32).toString("hex"));' > /qa/home/fixture-jwt
  export GENIE_CI_FRESH_JWT="$(cat /qa/home/fixture-jwt)"
  stage=preload-native-artifacts
  run_stage /qa/prepare.log /qa/supabase stack install --runtime native
  stage=check-native-lock
  [[ -s supabase/supabase.lock ]]
  echo 'Official native services preloaded; no tests ran in networked preparation.'
  exit 0
fi
[[ "${1:-}" == smoke ]]
stage=namespace
# Prove loopback-only network by its Linux interface, not a public probe.
[[ "$(ls -1 /sys/class/net)" == lo && ! -S /var/run/docker.sock ]]
[[ "$(awk 'END {print NR}' /proc/net/route)" == 1 ]]
[[ ! -e supabase/.env && ! -e supabase/functions/.env ]]
export GENIE_CI_FRESH_JWT="$(cat /qa/home/fixture-jwt)"
stage=check-native-lock
[[ -s supabase/supabase.lock ]]
stage=first-start
run_stage /qa/first.log /qa/supabase stack start --runtime native --frozen
stage=verify-local-status
/qa/supabase stack status --output-format json >/qa/status.json 2>/qa/status.err
node /qa/status-guard.mjs /qa/status.json /qa/home/fixture-jwt /qa/local-keys.json supabase/functions/.env
stage=edge-restart
run_stage /qa/stop.log /qa/supabase stack stop
run_stage /qa/second.log /qa/supabase stack start --runtime native --frozen
/qa/supabase stack status --output-format json >/qa/status-after.json 2>/qa/status-after.err
stage=check-runtime-keys
node /qa/status-guard.mjs /qa/status-after.json /qa/home/fixture-jwt /qa/local-keys-after.json /qa/check-only.env
cmp -s /qa/local-keys.json /qa/local-keys-after.json
stage=run-auth-rest-rls
# Only pass the local public JWT to the smoke. Keep key files out of logs.
node --input-type=module -e '
  import fs from "node:fs"; import {spawnSync} from "node:child_process";
  const status=JSON.parse(fs.readFileSync("/qa/local-keys.json","utf8"));
  const run=spawnSync(process.execPath,["/qa/verify-loopback.mjs","--run"],{encoding:"utf8",timeout:150000,
    env:{GENIE_CONFIRM:"isolated-genie-synthetic-only",GENIE_SUPABASE_URL:"http://127.0.0.1:55321",GENIE_SUPABASE_PUBLIC_KEY:status.anon}});
  if(run.status!==0 || !run.stdout.includes("PASS: local Auth, Edge, PostgREST"))process.exit(1);
  process.stdout.write("Verified local Auth, PostgREST owner isolation, voting, tally and single-record deletion.\n");
'
